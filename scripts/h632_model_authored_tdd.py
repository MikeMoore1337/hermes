def sha(data: str) -> str:
    return hashlib.sha256(data.encode("utf-8")).hexdigest()


def source(raw: str) -> str:
    if not isinstance(raw, str) or not raw.strip() or len(raw) > 2000:
        raise ValueError("Missing or oversized model-authored source")
    text = raw.strip()
    fence = chr(96) * 3
    if text.startswith(fence):
        matched = re.fullmatch(r"\x60{3}(?:python|py)?\s*\n(.*?)\n\x60{3}", text, re.S)
        if not matched:
            raise ValueError("Malformed fenced source")
        text = matched.group(1).strip()
    if "\x00" in text or "\r" in text or fence in text:
        raise ValueError("Unsafe source encoding")
    return text + "\n"


def integer(node: ast.AST) -> int:
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
        return -integer(node.operand)
    if not isinstance(node, ast.Constant) or type(node.value) is not int:
        raise ValueError("Only fixed integer test operands allowed")
    return node.value


def check_tests(code: str) -> None:
    tree = ast.parse(code, filename="test_calc.py")
    if len(tree.body) != 3:
        raise ValueError("Expected import and exactly two regression tests")
    imp = tree.body[0]
    if (not isinstance(imp, ast.ImportFrom) or imp.module != "calc" or imp.level != 0
            or len(imp.names) != 1 or imp.names[0].name != "add" or imp.names[0].asname):
        raise ValueError("Unexpected test import")
    seen = {}
    for fn in tree.body[1:]:
        if (not isinstance(fn, ast.FunctionDef) or fn.name not in CASES
                or fn.decorator_list or fn.args.posonlyargs or fn.args.args
                or fn.args.kwonlyargs or fn.args.vararg or fn.args.kwarg
                or fn.args.defaults or fn.args.kw_defaults
                or len(fn.body) != 1 or not isinstance(fn.body[0], ast.Assert)
                or fn.body[0].msg is not None):
            raise ValueError("Unsafe test function shape")
        compare = fn.body[0].test
        if (not isinstance(compare, ast.Compare) or len(compare.ops) != 1
                or not isinstance(compare.ops[0], ast.Eq) or len(compare.comparators) != 1
                or not isinstance(compare.left, ast.Call)
                or not isinstance(compare.left.func, ast.Name)
                or compare.left.func.id != "add" or compare.left.keywords
                or len(compare.left.args) != 2):
            raise ValueError("Test must assert add(a,b) equals a literal")
        actual = (*[integer(a) for a in compare.left.args], integer(compare.comparators[0]))
        if actual != CASES[fn.name] or fn.name in seen:
            raise ValueError("Wrong test operands or duplicate test")
        seen[fn.name] = actual
    if seen != CASES:
        raise ValueError("Missing positive or negative regression test")


def check_fix(code: str) -> None:
    tree = ast.parse(code, filename="calc.py")
    if len(tree.body) != 1 or not isinstance(tree.body[0], ast.FunctionDef):
        raise ValueError("Only add() may be implemented")
    fn = tree.body[0]
    args = fn.args
    if (fn.name != "add" or fn.decorator_list or args.posonlyargs or args.vararg
            or args.kwarg or args.kwonlyargs or args.defaults or args.kw_defaults
            or [a.arg for a in args.args] != ["a", "b"]):
        raise ValueError("Unsafe function signature")
    for annotation in [a.annotation for a in args.args] + [fn.returns]:
        if annotation is not None and (
                not isinstance(annotation, ast.Name) or annotation.id != "int"):
            raise ValueError("Unexpected type annotation")
    body = fn.body
    if (body and isinstance(body[0], ast.Expr)
            and isinstance(body[0].value, ast.Constant)
            and type(body[0].value.value) is str):
        body = body[1:]
    if len(body) != 1 or not isinstance(body[0], ast.Return):
        raise ValueError("Unexpected implementation statements")
    result = body[0].value
    if (not isinstance(result, ast.BinOp) or not isinstance(result.op, ast.Add)
            or not isinstance(result.left, ast.Name) or result.left.id != "a"
            or not isinstance(result.right, ast.Name) or result.right.id != "b"):
        raise ValueError("Only the safe addition expression is accepted")


def check_root(root: Path) -> Path:
    if (not root.is_absolute() or root.name != "h632-model-authored-tdd"
            or root.parent.name != "fixture" or root.parent.parent.name != "test-home"):
        raise ValueError("Not a disposable H632 synthetic root")
    for parent in (root.parent.parent, root.parent):
        if not stat.S_ISDIR(parent.lstat().st_mode):
            raise ValueError("Symlink/unsafe H632 fixture parent")
    if root.is_symlink() or (root.exists() and
                            (not root.is_dir() or any(root.iterdir()))):
        raise ValueError("Unsafe or nonempty H632 fixture root")
    return root


def call(root: Path, command: list[str]) -> subprocess.CompletedProcess[str]:
    env = dict(os.environ)
    env.update({"GIT_CONFIG_NOSYSTEM": "1", "GIT_CONFIG_GLOBAL": "/dev/null",
                "GIT_TERMINAL_PROMPT": "0", "PYTHONDONTWRITEBYTECODE": "1",
                "PYTHONNOUSERSITE": "1", "PYTHONPATH": ""})
    return subprocess.run(command, cwd=root, text=True, capture_output=True,
                          timeout=15, check=False, env=env)


def git(root: Path, *args: str) -> str:
    cmd = ["git", "-c", "core.hooksPath=/dev/null",
           "-c", "user.name=H632 Synthetic", "-c", "user.email=h632@invalid.test",
           *args]
    p = call(root, cmd)
    if p.returncode:
        raise AssertionError("Synthetic git step failed: " + " ".join(args))
    return p.stdout.strip()


def tests(root: Path) -> dict:
    p = call(root, [sys.executable, "run_tests.py"])
    if p.returncode not in (0, 1):
        raise AssertionError("Test process failed outside assertions")
    try:
        report = json.loads(p.stdout)
    except ValueError as exc:
        raise AssertionError("Test runner returned no structured result") from exc
    if report.get("count") != 2 or not isinstance(report.get("errors"), list):
        raise AssertionError("Test count not proven")
    return {"exit": p.returncode, **report}


def coverage(root: Path) -> float:
    sys.path.insert(0, str(root))
    try:
        sys.modules.pop("calc", None)
        sys.modules.pop("test_calc", None)
        tests_module = importlib.import_module("test_calc")
        tracker = trace.Trace(count=True, trace=False)
        for name in CASES:
            tracker.runfunc(getattr(tests_module, name))
        hits = {line for (filename, line), n in tracker.results().counts.items()
                if Path(filename).resolve() == (root / "calc.py").resolve() and n > 0}
        returns = {x.lineno for x in ast.walk(ast.parse((root / "calc.py").read_text()))
                   if isinstance(x, ast.Return)}
        if not returns or not returns.issubset(hits):
            raise AssertionError("Model-generated return not covered by tests")
        return 100.0 * len(returns & hits) / len(returns)
    finally:
        sys.path.pop(0)
        sys.modules.pop("calc", None)
        sys.modules.pop("test_calc", None)


def execute(root: Path, generate_tests, generate_fix) -> dict:
    """Model must return test source BEFORE RED; fix is requested ONLY AFTER RED."""
    root = check_root(root)
    root.mkdir(mode=0o700, exist_ok=True)
    (root / "calc.py").write_text(BASE, encoding="utf-8")
    (root / "run_tests.py").write_text(RUNNER, encoding="utf-8")
    (root / ".gitignore").write_text("h632-model-authored-receipt.json\n"
                                      "h632-model-authored-proof.txt\n", encoding="utf-8")
    git(root, "init", "--quiet", "--initial-branch=main")
    git(root, "add", "calc.py", "run_tests.py", ".gitignore")
    git(root, "commit", "--quiet", "-m", "h632: synthetic buggy baseline")
    baseline_sha = git(root, "rev-parse", "HEAD")

    test_source = source(generate_tests())
    check_tests(test_source)
    (root / "test_calc.py").write_text(test_source, encoding="utf-8")
    red = tests(root)
    if (red["exit"] != 1 or len(red["errors"]) != 2 or
            {x.get("name") for x in red["errors"]} != set(CASES) or
            any(x.get("kind") != "AssertionError" for x in red["errors"])):
        raise AssertionError("RED did not fail twice on the genuine arithmetic bug")
    git(root, "add", "test_calc.py")
    git(root, "commit", "--quiet", "-m", "test(h632): model-authored RED")
    red_sha = git(root, "rev-parse", "HEAD")

    fixed_source = source(generate_fix())
    check_fix(fixed_source)
    (root / "calc.py").write_text(fixed_source, encoding="utf-8")
    green = tests(root)
    if green != {"exit": 0, "count": 2, "errors": []}:
        raise AssertionError("GREEN failed to pass both model-authored regression tests")
    measured = coverage(root)
    if measured < 80:
        raise AssertionError("Model-generated code not sufficiently covered")
    git(root, "add", "calc.py")
    git(root, "commit", "--quiet", "-m", "fix(h632): model-authored GREEN")
    green_sha = git(root, "rev-parse", "HEAD")
    if (len({baseline_sha, red_sha, green_sha}) != 3 or
            git(root, "rev-parse", "HEAD~1") != red_sha or
            git(root, "rev-parse", "HEAD~2") != baseline_sha or
            git(root, "status", "--porcelain")):
        raise AssertionError("Missing or dirty synthetic Git checkpoints")
    result = {
        "schema": "hermes-h632-model-authored-tdd-v1",
        "status": "PASS_MODEL_WRITTEN_RED_GREEN",
        "scope": "GUIDED_MODEL_WRITTEN_SYNTHETIC_TDD",
        "autonomous_step_selection": False,
        "model_wrote_regression_tests": True,
        "model_wrote_fix_after_observed_red": True,
        "test_source_sha256": sha(test_source),
        "fixed_source_sha256": sha(fixed_source),
        "initial_bug_sha256": sha(BASE),
        "red": red, "green": green,
        "return_coverage_percent": measured,
        "git_checkpoints": [baseline_sha, red_sha, green_sha],
    }
    (root / "h632-model-authored-receipt.json").write_text(
        json.dumps(result, sort_keys=True, indent=2) + "\n", encoding="utf-8")
    (root / "h632-model-authored-proof.txt").write_text(MARKER, encoding="utf-8")
    return result
